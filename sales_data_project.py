import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

#read file
df = pd.read_excel("/content/drive/MyDrive/Data analysis Techpanda/Final_Project_1/Python_cleaning/clean_sales_dataset_project.xlsx")

#display column heads
df.head()

#row x columns
df.shape

#list the column headers
df.columns

df.info()#display datatypes of each columns

df.isna().sum()#sum of null values in each column

df.duplicated().sum()#check for duplicate rows if not we get 0

#make a copy of original data
df.copy()

#Removing the empty column
df=df.drop(columns=["Unnamed: 9"],errors="ignore")

#remove duplicate rows
df=df.drop_duplicates()

#Standrdize region,Product text by removing unwanted space,converted to string type nd made titlecase
df["Region"]=(df["Region"].astype(str)).str.strip().str.title()
df["Product"]=(df["Product"].astype(str)).str.strip().str.title()

#convert the order_date to type date

df['Order_Date'] = pd.to_datetime(df['Order_Date'],errors='coerce')

#calculate missing sales if only both the quantity and price exxist
calculate_sales=(df['Sales'].isna() & df['Quantity'].notna() & df['Price'].notna())
df.loc[calculate_sales,'Sales']=(df['Quantity']*df['Price'])

df["Customer_Name"] = df["Customer_Name"].fillna("Unknown Customer")

#verify
df.shape

df.isna().sum()

#usable sales values
df["Sales"].notna().sum()

#seperate analysis dataset
analysis_dif=df[df["Sales"].notna()].copy()

analysis_dif.shape

"""# **Business questions**

**1. Top selling products**
"""

product_sales = (
    analysis_dif
    .groupby("Product")["Sales"]
    .sum()
    .sort_values(ascending=False)
)

product_sales

#chart for this
plt.figure(figsize=(8, 5))

product_sales.plot(kind="bar")

plt.title("Top-Selling Products by Revenue")
plt.xlabel("Product")
plt.ylabel("Total Sales (₹)")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

"""**2. Region with the highest revenue**"""

region_sales=(
    analysis_dif
    .groupby("Region")["Sales"]
    .sum()
    .sort_values(ascending=False)
)
region_sales

#visualize this table sales by region
plt.figure(figsize=(8, 5))
region_sales = region_sales.sort_values(ascending=True)
region_sales.plot(kind="barh",color="#00008B",width=0.6)

plt.title("Sales by Region")
plt.xlabel("Region")
plt.ylabel("Total Sales (₹)")
plt.xticks(rotation=0)
plt.tight_layout()
plt.show()

"""**3. Monthly sales trend**"""

#create month column
analysis_dif["Month"]=(analysis_dif["Order_Date"].dt.month)
analysis_dif["Month"]

#Group the sales by month
monthly_sales=(
    analysis_dif
    .dropna(subset=["Order_Date"])
    .groupby("Month")["Sales"]
    .sum()
)
monthly_sales

plt.figure(figsize=(10, 5))

monthly_sales.plot(kind="line", marker="o")

plt.title("Monthly Sales Trend")
plt.xlabel("Month")
plt.ylabel("Total Sales (₹)")
plt.xticks(rotation=45)
plt.grid(True)
plt.tight_layout()
plt.show()

summary = pd.DataFrame({
    "Metric": [
        "Total Revenue",
        "Total Orders",
        "Orders with Usable Revenue",
        "Average Order Value"
    ],
    "Value": [
        analysis_dif["Sales"].sum(),
        len(df),
        analysis_dif["Sales"].notna().sum(),
        analysis_dif["Sales"].mean()
    ]
})

summary

